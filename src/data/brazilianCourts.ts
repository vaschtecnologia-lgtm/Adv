/**
 * Detects court from CNJ format NNNNNNN-DD.AAAA.J.TR.OOOO
 */
export function identifyCourtFromCNJ(cnj: string): BrazilianCourt | null {
  const clean = cnj.replace(/[^0-9]/g, '');
  if (clean.length < 14) return null;

  // Align from the right (supporting missing leading zeros)
  const j = clean.slice(-7, -6);
  const tr = clean.slice(-6, -4);
  const code = `${j}.${tr}`;

  const match = ALL_BRAZILIAN_COURTS.find((c) => c.codeCNJ === code);
  if (match) return match;

  // Dynamically resolve state courts (TJ)
  if (j === '8') {
    const stateDetails: Record<string, { sigla: string; name: string; state: string }> = {
      '01': { sigla: 'TJAC', name: 'Tribunal de Justiça do Acre', state: 'AC' },
      '02': { sigla: 'TJAL', name: 'Tribunal de Justiça de Alagoas', state: 'AL' },
      '03': { sigla: 'TJAM', name: 'Tribunal de Justiça do Amazonas', state: 'AM' },
      '04': { sigla: 'TJAP', name: 'Tribunal de Justiça do Amapá', state: 'AP' },
      '05': { sigla: 'TJBA', name: 'Tribunal de Justiça da Bahia', state: 'BA' },
      '06': { sigla: 'TJCE', name: 'Tribunal de Justiça do Ceará', state: 'CE' },
      '07': { sigla: 'TJDFT', name: 'Tribunal de Justiça do Distrito Federal e dos Territórios', state: 'DF' },
      '08': { sigla: 'TJES', name: 'Tribunal de Justiça do Espírito Santo', state: 'ES' },
      '09': { sigla: 'TJGO', name: 'Tribunal de Justiça do Estado de Goiás', state: 'GO' },
      '10': { sigla: 'TJMA', name: 'Tribunal de Justiça do Maranhão', state: 'MA' },
      '11': { sigla: 'TJMT', name: 'Tribunal de Justiça de Mato Grosso', state: 'MT' },
      '12': { sigla: 'TJMS', name: 'Tribunal de Justiça de Mato Grosso do Sul', state: 'MS' },
      '13': { sigla: 'TJMG', name: 'Tribunal de Justiça de Minas Gerais', state: 'MG' },
      '14': { sigla: 'TJPA', name: 'Tribunal de Justiça do Pará', state: 'PA' },
      '15': { sigla: 'TJPB', name: 'Tribunal de Justiça da Paraíba', state: 'PB' },
      '16': { sigla: 'TJPR', name: 'Tribunal de Justiça do Paraná', state: 'PR' },
      '17': { sigla: 'TJPE', name: 'Tribunal de Justiça de Pernambuco', state: 'PE' },
      '18': { sigla: 'TJPI', name: 'Tribunal de Justiça do Piauí', state: 'PI' },
      '19': { sigla: 'TJRJ', name: 'Tribunal de Justiça do Rio de Janeiro', state: 'RJ' },
      '20': { sigla: 'TJRN', name: 'Tribunal de Justiça do Rio Grande do Norte', state: 'RN' },
      '21': { sigla: 'TJRS', name: 'Tribunal de Justiça do Rio Grande do Sul', state: 'RS' },
      '22': { sigla: 'TJRO', name: 'Tribunal de Justiça de Rondônia', state: 'RO' },
      '23': { sigla: 'TJRR', name: 'Tribunal de Justiça de Roraima', state: 'RR' },
      '24': { sigla: 'TJSC', name: 'Tribunal de Justiça de Santa Catarina', state: 'SC' },
      '25': { sigla: 'TJSE', name: 'Tribunal de Justiça de Sergipe', state: 'SE' },
      '26': { sigla: 'TJSP', name: 'Tribunal de Justiça de São Paulo', state: 'SP' },
      '27': { sigla: 'TJTO', name: 'Tribunal de Justiça do Tocantins', state: 'TO' },
    };
    const details = stateDetails[tr] || { sigla: `TJ${tr}`, name: `Tribunal de Justiça da Região ${tr}`, state: 'BR' };
    return {
      sigla: details.sigla,
      name: details.name,
      instance: '2ª Instância',
      branch: 'Estadual / Distrital',
      state: details.state,
      codeCNJ: code,
      pjeUrl: `https://pje.tj${details.state.toLowerCase()}.jus.br`,
      description: `Jurisdição estadual abrangendo ${details.name}.`,
    };
  }

  // Dynamically resolve labor courts (TRT)
  if (j === '5') {
    const trNumber = parseInt(tr, 10);
    const regionStates: Record<string, string> = {
      '01': 'RJ', '02': 'SP', '03': 'MG', '04': 'RS', '05': 'BA', '06': 'PE', '07': 'CE', '08': 'PA',
      '09': 'PR', '10': 'DF', '11': 'AM', '12': 'SC', '13': 'PB', '14': 'RO', '15': 'SP', '16': 'MA',
      '17': 'ES', '18': 'GO', '19': 'AL', '20': 'SE', '21': 'RN', '22': 'PI', '23': 'MT', '24': 'MS'
    };
    const state = regionStates[tr] || 'DF';
    return {
      sigla: `TRT${trNumber}`,
      name: `Tribunal Regional do Trabalho da ${trNumber}ª Região (${state})`,
      instance: '2ª Instância',
      branch: 'Trabalhista',
      state,
      codeCNJ: code,
      pjeUrl: `https://pje.trt${trNumber}.jus.br`,
      description: `Justiça do Trabalho da ${trNumber}ª Região.`,
    };
  }

  // Dynamically resolve federal regional courts (TRF)
  if (j === '4') {
    const trNumber = parseInt(tr, 10);
    const trfStates: Record<string, string> = {
      '01': 'DF', '02': 'RJ', '03': 'SP', '04': 'RS', '05': 'PE', '06': 'MG'
    };
    const state = trfStates[tr] || 'DF';
    return {
      sigla: `TRF${trNumber}`,
      name: `Tribunal Regional Federal da ${trNumber}ª Região`,
      instance: '2ª Instância',
      branch: 'Federal',
      state,
      codeCNJ: code,
      pjeUrl: `https://pje1g.trf${trNumber}.jus.br`,
      description: `Justiça Federal da ${trNumber}ª Região.`,
    };
  }

  return null;
}
